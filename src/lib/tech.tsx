export type TechKey = keyof typeof techStack;

export function isTechKey(value: string): value is TechKey {
  return value in techStack;
}

/** Resolve a tech key to label + icon; unknown keys get a generic icon. */
export function resolveTech(key: string): TechEntry {
  if (isTechKey(key)) return techStack[key];
  return { label: key, Icon: FaCode };
}

/** True only for a repository URL (github.com/<owner>/<repo>), not a profile or marketing page. */
export function isRepoLink(href?: string): href is string {
  if (!href) return false;
  try {
    const url = new URL(href);
    return (
      url.hostname === "github.com" &&
      url.pathname.split("/").filter(Boolean).length >= 2
    );
  } catch {
    return false;
  }
}
